import {
  drawGlitchOverlay,
  drawWaveform,
  scoreToState,
  stateColor,
} from "./waveform.js";

export interface CardOptions {
  link: string;
  title: string;
  pulseScore: number;
  txHash: string;
  topTopics: string[];
}

function truncateLink(link: string, max = 48): string {
  if (link.length <= max) return link;
  return link.slice(0, max - 3) + "...";
}

function platformFromLink(link: string): string {
  if (link.includes("tiktok")) return "TikTok";
  if (link.includes("reddit")) return "Reddit";
  if (link.includes("youtube") || link.includes("youtu.be")) return "YouTube";
  if (link.includes("x.com") || link.includes("twitter")) return "X";
  return "Web";
}

export function renderPulseCard(
  canvas: HTMLCanvasElement,
  options: CardOptions
): void {
  const ctx = canvas.getContext("2d");
  if (!ctx) return;

  const w = canvas.width;
  const h = canvas.height;
  const state = scoreToState(options.pulseScore);
  const color = stateColor(state);

  ctx.fillStyle = "#0a0a0f";
  ctx.fillRect(0, 0, w, h);

  const gradient = ctx.createLinearGradient(0, 0, w, h);
  gradient.addColorStop(0, "rgba(0, 255, 136, 0.05)");
  gradient.addColorStop(1, "rgba(255, 0, 102, 0.05)");
  ctx.fillStyle = gradient;
  ctx.fillRect(0, 0, w, h);

  ctx.strokeStyle = "#2a2a3a";
  ctx.lineWidth = 2;
  ctx.strokeRect(20, 20, w - 40, h - 40);

  ctx.font = "700 48px 'Space Grotesk', sans-serif";
  ctx.fillStyle = "#e8e8f0";
  ctx.fillText("CULTURE PULSE", 60, 100);

  ctx.font = "400 24px 'JetBrains Mono', monospace";
  ctx.fillStyle = color;
  ctx.fillText(`$SIGNAL // ${options.pulseScore}`, 60, 145);

  drawWaveform(ctx, 60, 180, w - 120, 120, options.pulseScore, color);

  ctx.font = "600 36px 'Space Grotesk', sans-serif";
  ctx.fillStyle = "#e8e8f0";
  const title =
    options.title || "Cultural moment detected";
  ctx.fillText(title.slice(0, 40), 60, 360);

  ctx.font = "400 20px 'JetBrains Mono', monospace";
  ctx.fillStyle = "#8888a0";
  ctx.fillText(`${platformFromLink(options.link)} · ${truncateLink(options.link)}`, 60, 400);

  if (options.topTopics.length > 0) {
    ctx.fillText(
      `Topics: ${options.topTopics.slice(0, 3).join(" · ")}`,
      60,
      435
    );
  }

  ctx.font = "400 16px 'JetBrains Mono', monospace";
  ctx.fillStyle = "#555566";
  ctx.fillText(`Pulse Event tx: ${options.txHash.slice(0, 20)}...`, 60, h - 80);
  ctx.fillText("Generated by Signal Forge · signal.forge", 60, h - 50);

  if (state === "peak") {
    drawGlitchOverlay(ctx, w, h);
  }
}
